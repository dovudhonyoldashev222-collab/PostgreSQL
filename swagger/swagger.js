const swaggerUi = require("swagger-ui-express");
const { resources } = require("../routes/resourceRoutes");

const toOpenApiType = (attribute) => {
    const type = attribute.type.key;

    if (["INTEGER", "BIGINT", "SMALLINT"].includes(type)) {
        return { type: "integer" };
    }
    if (["FLOAT", "DOUBLE", "REAL", "DECIMAL"].includes(type)) {
        return { type: "number" };
    }
    if (type === "BOOLEAN") {
        return { type: "boolean" };
    }
    if (type === "DATEONLY") {
        return { type: "string", format: "date" };
    }
    if (type === "DATE") {
        return { type: "string", format: "date-time" };
    }
    if (type === "TIME") {
        return { type: "string", format: "time" };
    }
    if (type === "JSON" || type === "JSONB") {
        return { type: "object", additionalProperties: true };
    }

    return { type: "string" };
};

const paths = {};
const schemas = {};
const errorSchema = {
    type: "object",
    properties: {
        message: {
            oneOf: [
                { type: "string" },
                { type: "array", items: { type: "string" } },
            ],
        },
    },
};

resources.forEach(({ name, path, model }) => {
    const attributes = Object.entries(model.rawAttributes).filter(
        ([, attribute]) => !attribute._autoGenerated
    );
    const properties = Object.fromEntries(
        attributes.map(([attributeName, attribute]) => [
            attributeName,
            toOpenApiType(attribute),
        ])
    );
    const responseProperties = Object.fromEntries(
        Object.entries(properties).filter(([attributeName]) =>
            !["password", "hashed_password", "hashed_refresh_token", "card_number"].includes(attributeName) &&
            !(name === "CustomerCard" && attributeName === "number")
        )
    );
    const writableProperties = Object.fromEntries(
        Object.entries(properties).filter(([attributeName]) => attributeName !== "id")
    );
    const customerCreateFields = new Set([
        "first_name",
        "last_name",
        "phone",
        "hashed_password",
        "email",
    ]);
    const customerUpdateFields = new Set([
        ...customerCreateFields,
        "birth_date",
        "gender_id",
    ]);
    const createProperties =
        name === "Customer"
            ? Object.fromEntries(
                  Object.entries(writableProperties).filter(([field]) =>
                      customerCreateFields.has(field)
                  )
              )
            : writableProperties;
    const updateProperties =
        name === "Customer"
            ? Object.fromEntries(
                  Object.entries(writableProperties).filter(([field]) =>
                      customerUpdateFields.has(field)
                  )
              )
            : writableProperties;
    const required = attributes
        .filter(([, attribute]) =>
            !attribute.primaryKey &&
            !attribute._autoGenerated &&
            !attribute.allowNull &&
            attribute.defaultValue === undefined
        )
        .map(([attributeName]) => attributeName);
    const createRequired =
        name === "Customer"
            ? ["first_name", "last_name", "phone", "hashed_password", "email"]
            : required;

    schemas[name] = { type: "object", properties: responseProperties };
    if (name === "User") {
        schemas[name].properties.customer = {
            $ref: "#/components/schemas/Customer",
        };
    }
    const dataSchema = { $ref: `#/components/schemas/${name}` };
    const successSchema = (data, includeMessage = false) => ({
        type: "object",
        properties: {
            ...(includeMessage ? { message: { type: "string" } } : {}),
            data,
        },
        required: ["data"],
    });
    const response = (description, schema) => ({
        description,
        content: {
            "application/json": { schema },
        },
    });
    const includeMessage = name === "Customer";
    paths[`/api/${path}`] = {
        get: {
            tags: [name],
            summary: `List ${path}`,
            responses: {
                200: response(
                    "Records returned",
                    successSchema({ type: "array", items: dataSchema }, includeMessage)
                ),
                500: response("Server error", errorSchema),
            },
        },
        post: {
            tags: [name],
            summary: `Create ${name}`,
            requestBody: {
                required: true,
                content: {
                    "application/json": {
                        schema: {
                            type: "object",
                            properties: createProperties,
                            required: createRequired,
                            additionalProperties: false,
                        },
                    },
                },
            },
            responses: {
                201: response("Record created", successSchema(dataSchema, includeMessage)),
                400: response("Invalid input", errorSchema),
                409: response("Duplicate value", errorSchema),
                500: response("Server error", errorSchema),
            },
        },
    };
    paths[`/api/${path}/{id}`] = {
        get: {
            tags: [name],
            summary: `Get ${name} by ID`,
            parameters: [{ $ref: "#/components/parameters/recordId" }],
            responses: {
                200: response("Record returned", successSchema(dataSchema, includeMessage)),
                400: response("Invalid ID", errorSchema),
                404: response("Record not found", errorSchema),
                500: response("Server error", errorSchema),
            },
        },
        put: {
            tags: [name],
            summary: `Update ${name}`,
            parameters: [{ $ref: "#/components/parameters/recordId" }],
            requestBody: {
                required: true,
                content: {
                    "application/json": {
                        schema: {
                            type: "object",
                            properties: updateProperties,
                            minProperties: 1,
                            additionalProperties: false,
                        },
                    },
                },
            },
            responses: {
                200: response("Record updated", successSchema(dataSchema, includeMessage)),
                400: response("Invalid input", errorSchema),
                404: response("Record not found", errorSchema),
                409: response("Duplicate value", errorSchema),
                500: response("Server error", errorSchema),
            },
        },
        delete: {
            tags: [name],
            summary: `Delete ${name}`,
            parameters: [{ $ref: "#/components/parameters/recordId" }],
            responses: {
                200: response(
                    "Record deleted",
                    includeMessage ? { $ref: "#/components/schemas/Message" } : errorSchema
                ),
                400: response("Invalid ID", errorSchema),
                404: response("Record not found", errorSchema),
                409: response("Record is referenced by another record", errorSchema),
                500: response("Server error", errorSchema),
            },
        },
    };
});

paths["/api/users/search"] = {
    get: {
        tags: ["User"],
        summary: "Search users by name or email",
        parameters: [
            {
                name: "query",
                in: "query",
                required: true,
                schema: { type: "string", minLength: 1 },
                description: "Search term matched against user name and email",
            },
        ],
        responses: {
            200: {
                description: "Matching users returned",
                content: {
                    "application/json": {
                        schema: {
                            type: "object",
                            properties: {
                                data: {
                                    type: "array",
                                    items: { $ref: "#/components/schemas/User" },
                                },
                            },
                            required: ["data"],
                        },
                    },
                },
            },
            400: {
                description: "Search query is required",
                content: { "application/json": { schema: errorSchema } },
            },
            500: {
                description: "Server error",
                content: { "application/json": { schema: errorSchema } },
            },
        },
    },
};

const swaggerSpec = {
    openapi: "3.0.0",
    info: {
        title: "Ticket booking API",
        version: "1.0.0",
        description: "CRUD API generated from the Sequelize models, including user search.",
    },
    paths,
    components: {
        schemas: {
            ...schemas,
            Message: errorSchema,
        },
        parameters: {
            recordId: {
                name: "id",
                in: "path",
                required: true,
                schema: { type: "integer", minimum: 1 },
            },
        },
    },
};

const setupSwagger = (app) => {
    app.use(
        "/api-docs",
        swaggerUi.serve,
        swaggerUi.setup(swaggerSpec, {
            swaggerOptions: {
                defaultModelsExpandDepth: -1,
                displayRequestDuration: true,
            },
        })
    );
};

module.exports = setupSwagger;
module.exports.swaggerSpec = swaggerSpec;
